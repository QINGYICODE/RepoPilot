// Local end-to-end verification. Calls the configured model on prepared real repository snapshots.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const root = path.resolve(__dirname, '..'), baseUrl = process.env.REPOPILOT_PREVIEW_URL || 'http://127.0.0.1:5173'
async function main() {
  await fs.mkdir(path.join(root, '.local'), { recursive: true })
  const browser = await chromium.launch({ headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] })
    const page = await context.newPage(), errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(baseUrl)
    await page.getByRole('button', { name: /填入真实仓库示例/ }).waitFor()
    await page.locator('.example-button').click()
    await page.getByRole('button', { name: '开始分析', exact: true }).waitFor()
    await page.waitForFunction(() => !document.querySelector('.composer button[type="submit"]').disabled)
    assert((await page.locator('#analysis-question').inputValue()).includes('3.4.1'))
    assert(!(await page.locator('#analysis-scope').count()), 'Advanced scope is collapsed by default')
    await page.screenshot({ path: path.join(root, '.local/redesign-home.png'), fullPage: true })
    await page.getByRole('button', { name: '开始分析', exact: true }).click()
    const result = page.locator('[data-testid="analysis-result"][data-reason="EVIDENCE_VERIFIED"]')
    await result.waitFor({ timeout: 100000 })
    const impactId = new URL(page.url()).searchParams.get('run')
    const impact = await (await page.request.get(`${baseUrl}/api/analysis-runs/${impactId}`)).json()
    assert.deepEqual(impact.dependency.affectedServices, ['spring-petclinic-admin-server'])
    assert((await result.innerText()).includes('1 个服务受到声明依赖影响'))
    assert.equal(await page.locator('.execution-details').getAttribute('open'), null, 'Execution details stay secondary')
    await page.getByRole('button', { name: '查看原文证据', exact: true }).click()
    await page.getByRole('dialog', { name: '原文证据' }).waitFor()
    assert((await page.locator('.source-code').innerText()).includes('dependency'))
    await page.getByRole('button', { name: '复制 SHA', exact: true }).click()
    await page.getByRole('button', { name: '已复制 SHA', exact: true }).waitFor()
    assert.match(await page.evaluate(() => navigator.clipboard.readText()), /^[a-f0-9]{40}$/)
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('dialog[open]').count(), 0)
    await page.screenshot({ path: path.join(root, '.local/redesign-impact.png'), fullPage: true })
    await page.reload(); await result.waitFor()
    assert.equal(new URL(page.url()).searchParams.get('run'), impactId)
    assert.equal(await page.getByRole('link', { name: /依赖影响分析/ }).count(), 1)
    console.log('Dependency analysis, evidence drawer, clipboard, Escape and refresh verified')

    await page.getByRole('radio', { name: '查找历史修复', exact: true }).check()
    await page.locator('.example-button').click()
    await page.waitForFunction(() => !document.querySelector('.composer button[type="submit"]').disabled)
    await page.getByRole('button', { name: '开始分析', exact: true }).click()
    await result.waitFor({ timeout: 100000 })
    assert((await result.innerText()).includes('fix: zipkin tracing'))
    assert((await result.innerText()).includes('尚不能确认'))
    const fixId = new URL(page.url()).searchParams.get('run')
    await page.getByRole('button', { name: '查看修改证据', exact: true }).first().click()
    await page.getByRole('dialog').waitFor()
    assert.match(await page.locator('.source-code').innerText(), /zipkin|tracing/i)
    await page.keyboard.press('Escape')
    await page.screenshot({ path: path.join(root, '.local/redesign-incident.png'), fullPage: true })
    await page.getByRole('link', { name: /依赖影响分析/ }).click(); await result.waitFor()
    assert.equal(new URL(page.url()).searchParams.get('run'), impactId, 'Recent run restores a different task')
    await page.getByRole('link', { name: /历史修复分析/ }).click(); await result.waitFor()
    assert.equal(new URL(page.url()).searchParams.get('run'), fixId)
    console.log('Historical fix and switching recent runs verified')

    await page.getByRole('button', { name: '调整范围', exact: true }).click()
    assert(await page.getByLabel('查阅的代码版本', { exact: true }).isVisible())
    assert((await page.getByLabel('查阅的代码版本', { exact: true }).locator('option').allTextContents()).some(s => s.includes(' ')))
    await page.getByRole('button', { name: '收起范围', exact: true }).click()
    for (const [question, reason, visibleText] of [
      ['告警 NO_SUCH_REPO_SIGNATURE_987654321，请查询历史修复 commit。', 'NO_EVIDENCE', '没有找到足够的代码证据'],
      ['今天天气怎么样？', 'OUT_OF_SCOPE', '这个问题超出了仓库分析范围'],
      ['请查 https://github.com/other/repo 的异常修复', 'FORBIDDEN', '请求超出了当前授权范围'],
    ]) {
      await page.locator('#analysis-question').fill(question)
      await page.getByRole('button', { name: '开始分析', exact: true }).click()
      await page.locator(`[data-testid="analysis-result"][data-reason="${reason}"]`).waitFor({ timeout: 100000 })
      assert((await page.locator('[data-testid="analysis-result"]').innerText()).includes(visibleText))
    }
    await page.locator('.example-button').click()
    await page.waitForFunction(() => !document.querySelector('.composer button[type="submit"]').disabled)
    await page.getByRole('button', { name: '开始分析', exact: true }).click()
    await page.getByRole('button', { name: '取消分析', exact: true }).click()
    await page.locator('[data-testid="analysis-result"][data-status="CANCELLED"]').waitFor()
    await page.getByRole('link', { name: '仓库管理', exact: true }).first().click()
    await page.getByRole('heading', { name: '仓库管理', exact: true }).waitFor()
    await page.locator('.version-list .version-row').first().waitFor()
    await page.getByRole('tab', { name: '代码检索', exact: true }).click()
    await page.getByRole('button', { name: '检索', exact: true }).click()
    await page.locator('.evidence-search-row').first().waitFor()
    await page.getByRole('tab', { name: '手动依赖比较', exact: true }).click()
    await page.getByRole('button', { name: '比较依赖', exact: true }).click()
    await page.getByRole('heading', { name: /个服务存在声明依赖影响/ }).waitFor()
    await page.getByRole('link', { name: '使用指南', exact: true }).click()
    await page.getByRole('link', { name: '试试依赖影响分析' }).click()
    await page.waitForFunction(() => document.querySelector('#analysis-question')?.value.includes('3.4.1'))
    await page.screenshot({ path: path.join(root, '.local/redesign-desktop.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 }); await page.evaluate(() => window.scrollTo(0, 0))
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile page overflows')
    await page.getByRole('button', { name: '打开导航', exact: true }).click()
    await page.getByRole('link', { name: '使用指南', exact: true }).click()
    await page.getByRole('heading', { name: '使用指南', exact: true }).waitFor()
    await page.getByRole('link', { name: '试试告警历史修复' }).click()
    await page.waitForFunction(() => document.querySelector('#analysis-question')?.value.includes('zipkin'))
    await page.getByRole('button', { name: '填入真实仓库示例', exact: true }).click()
    assert((await page.locator('#analysis-question').inputValue()).includes('zipkin'))
    await page.screenshot({ path: path.join(root, '.local/redesign-mobile.png'), fullPage: true })
    assert.deepEqual(errors, [])

    const empty = await browser.newPage()
    await empty.route('**/api/repositories', route => route.fulfill({ json: [] }))
    await empty.goto(baseUrl)
    await empty.getByRole('heading', { name: '先接入一个 GitHub 仓库' }).waitFor()
    await empty.getByRole('link', { name: '接入仓库', exact: true }).waitFor()
    await empty.close()
    const offline = await browser.newPage()
    await offline.route('**/api/repositories', route => route.abort('failed'))
    await offline.goto(baseUrl)
    await offline.getByRole('alert').waitFor()
    assert.equal(await offline.getByRole('heading', { name: '先接入一个 GitHub 仓库' }).count(), 0, 'Network failure must not appear as an empty repository')
    await offline.getByRole('button', { name: '重新连接', exact: true }).waitFor()
    await offline.close()
    console.log(JSON.stringify({ passed: ['real dependency task', 'real historical fix', 'evidence drawer and copy', 'refresh and recent runs', 'scope controls', 'no evidence/scope/authorization refusal', 'repository versions and search', 'guide examples', 'mobile navigation', 'empty and network error states'], impactUsage: impact.usage }, null, 2))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error.message); process.exitCode = 1 })
