// Explicit local-browser smoke test. Uses the configured model; requires prepared real snapshots.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const baseUrl = 'http://127.0.0.1:5173'

async function main() {
  await fs.mkdir(path.join(root, '.local'), { recursive: true })
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(baseUrl)
    const repos = await (await page.request.get(`${baseUrl}/api/repositories`)).json()
    const repo = repos.find(r => `${r.owner}/${r.name}` === 'spring-petclinic/spring-petclinic-microservices')
    assert(repo, 'Import the real repository before running this smoke test')
    const snapshots = await (await page.request.get(`${baseUrl}/api/repositories/${repo.id}/snapshots`)).json()
    console.log('Loaded page:', (await page.locator('h1').allTextContents()).join(' '))
    const snapshot = sha => { const s = snapshots.find(s => s.commitSha === sha); assert(s, `Missing prepared snapshot ${sha}`); return String(s.id) }
    await page.getByLabel('GitHub 仓库', { exact: true }).selectOption(String(repo.id))
    const head = page.getByLabel('变更后版本 / HEAD', { exact: true })
    await head.locator('option').first().waitFor({ state: 'attached' })
    await head.selectOption(snapshot('597ad1fbfabadfef4ed8a1d475f7f34aa2666aab'))
    await page.getByLabel('变更前版本 / BASE', { exact: true }).selectOption(snapshot('17cad88d533554f53c634cfa78211ea2f51b0a46'))
    const module = page.getByLabel('模块范围', { exact: true })
    await module.locator('option[value="spring-petclinic-admin-server"]').waitFor({ state: 'attached' })
    await module.selectOption('spring-petclinic-admin-server')
    await page.locator('#analysis-question').fill('所选模块的依赖变更会影响哪些服务？请给出路径与证据。')
    await page.getByRole('button', { name: '开始分析 ↗', exact: true }).click()
    await page.locator('.analysis-result .phase-tag').filter({ hasText: /^EVIDENCE_VERIFIED$/ }).waitFor({ timeout: 100000 })
    console.log('Dependency task verified')
    assert((await page.locator('.analysis-result').innerText()).includes('spring-petclinic-admin-server'))
    await page.locator('.evidence-tabs button').first().click()
    await page.locator('.evidence-browser pre').waitFor()
    const firstRun = new URL(page.url()).searchParams.get('run')
    const impact = await (await page.request.get(`${baseUrl}/api/analysis-runs/${firstRun}`)).json()
    assert.deepEqual(impact.dependency.affectedServices, ['spring-petclinic-admin-server'])
    await page.screenshot({ path: path.join(root, '.local/analysis-preview.png'), fullPage: true })
    await page.reload()
    await page.locator('.analysis-result .phase-tag').filter({ hasText: /^EVIDENCE_VERIFIED$/ }).waitFor()
    assert.equal(new URL(page.url()).searchParams.get('run'), firstRun, 'Refresh must restore the same run')

    await page.getByRole('radio', { name: '告警历史修复', exact: true }).check()
    const knowledge = page.getByLabel('可查历史的知识版本', { exact: true })
    await knowledge.locator('option').first().waitFor({ state: 'attached' })
    await knowledge.selectOption(snapshot('3858f9c630cf989bb6809a86edf47c2be78dc9f1'))
    const service = page.getByLabel('告警归属模块', { exact: true })
    await service.locator('option[value="spring-petclinic-api-gateway"]').waitFor({ state: 'attached' })
    await service.selectOption('spring-petclinic-api-gateway')
    await page.locator('#analysis-question').fill('出现 zipkin tracing 告警，请查 spring-boot-starter-zipkin 的历史修复 commit。只能确认相似候选时请说明。')
    await page.getByRole('button', { name: '开始分析 ↗', exact: true }).click()
    await page.locator('.analysis-result .phase-tag').filter({ hasText: /^EVIDENCE_VERIFIED$/ }).waitFor({ timeout: 100000 })
    console.log('Incident task verified')
    assert((await page.locator('.analysis-result').innerText()).includes('9a76b4e34cd75f3d6bfa6f15775bf996c59e8989'))
    assert((await page.locator('.analysis-result').innerText()).includes('无法确认'))
    await page.screenshot({ path: path.join(root, '.local/incident-preview.png'), fullPage: true })

    await page.locator('#analysis-question').fill('告警 NO_SUCH_REPO_SIGNATURE_987654321，请查询历史修复 commit。')
    await page.getByRole('button', { name: '开始分析 ↗', exact: true }).click()
    await page.locator('.analysis-result .phase-tag').filter({ hasText: /^NO_EVIDENCE$/ }).waitFor({ timeout: 100000 })
    assert((await page.locator('.analysis-result').innerText()).includes('明确拒答'))

    await page.locator('#analysis-question').fill('今天天气怎么样？')
    await page.getByRole('button', { name: '开始分析 ↗', exact: true }).click()
    await page.locator('.analysis-result .phase-tag').filter({ hasText: /^OUT_OF_SCOPE$/ }).waitFor()
    assert((await page.locator('.analysis-result').innerText()).includes('明确拒答'))
    const other = await page.request.post(`${baseUrl}/api/analysis-runs`, { data: { repoId: repo.id, snapshotId: Number(snapshot('3858f9c630cf989bb6809a86edf47c2be78dc9f1')), task: 'INCIDENT_FIX', question: '请查 https://github.com/other/repo 的异常修复' } })
    assert.equal((await other.json()).reasonCode, 'FORBIDDEN')
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'Mobile viewport overflows')
    await page.screenshot({ path: path.join(root, '.local/analysis-mobile.png'), fullPage: true })
    assert.deepEqual(errors, [], 'Browser runtime errors')
    console.log(JSON.stringify({ passed: ['dependency analysis', 'evidence inspection', 'refresh recovery', 'historical fix candidate', 'no-evidence refusal', 'scope refusal', 'repository refusal', 'mobile layout'], impactUsage: impact.usage }, null, 2))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error.message); process.exitCode = 1 })
